"""Run PR-Sentinel (mock mode) over every case in benchmarks/cases and write RESULTS.md.

Case folders named bug_* contain a deliberate regression; clean_* are behaviour-preserving
refactors, so any finding there counts as a false positive.
"""
from __future__ import annotations

import platform
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import reporter  # noqa: E402
from src.cli import scan  # noqa: E402
from src.diff_parser import load_patch  # noqa: E402


def main() -> int:
    rows, correct, times = [], 0, []
    cases = sorted(p for p in (ROOT / "benchmarks" / "cases").iterdir() if p.is_dir())
    for case in cases:
        buggy = case.name.startswith("bug_")
        t0 = time.perf_counter()
        _, result = scan(load_patch(case / "change.patch", case), case)
        elapsed = time.perf_counter() - t0
        times.append(elapsed)
        st = reporter.status(result)
        flagged = st in ("fail", "review")
        ok = flagged == buggy
        correct += ok
        failed = [r for r in result.results if not r.passed]
        first = failed[0].case.call if failed else "-"
        rows.append(f"| `{case.name}` | {'bug' if buggy else 'clean'} | {st} | {len(result.results)} | "
                    f"{len(failed)} | `{first}` | {'yes' if ok else '**no**'} | {elapsed:.2f}s |")
        print(f"{case.name:34} {st:7} {'ok' if ok else 'MISS'} {elapsed:.2f}s")

    bugs = [c for c in cases if c.name.startswith("bug_")]
    caught = sum(1 for c, r in zip(cases, rows) if c.name.startswith("bug_") and "| yes |" in r)
    clean_ok = sum(1 for c, r in zip(cases, rows) if c.name.startswith("clean_") and "| yes |" in r)
    clean = len(cases) - len(bugs)
    summary = [
        "# Benchmark results",
        "",
        f"Generated by `python benchmarks/run_benchmarks.py` (mock mode, Python {platform.python_version()}, "
        f"{platform.system()}).",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Bugs detected | {caught}/{len(bugs)} ({caught / len(bugs):.0%}) |",
        f"| Clean refactors passed (no false positive) | {clean_ok}/{clean} |",
        f"| Overall accuracy | {correct}/{len(cases)} ({correct / len(cases):.0%}) |",
        f"| Mean time per case | {sum(times) / len(times):.2f}s |",
        f"| Total time | {sum(times):.2f}s |",
        "",
        "Status `fail` means a crash regression, `review` means a behaviour change, `pass` means no difference.",
        "",
        "| Case | Type | Status | Cases run | Flagged | First flagged input | Correct | Time |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    (ROOT / "benchmarks" / "RESULTS.md").write_text("\n".join(summary), encoding="utf-8")
    print(f"\n{correct}/{len(cases)} correct; wrote benchmarks/RESULTS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
